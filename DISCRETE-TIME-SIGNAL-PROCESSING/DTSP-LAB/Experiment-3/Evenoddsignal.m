clc;
clear all;
close all;
n = 0:1:4;
x = [0,1, 2, 3, 4];
xr = fliplr(x);
xe = (x+xr)/2;
xo = (x-xr)/2;
subplot(3,1,1);
stem(n,x);
xlabel("Time");
ylabel("Amplitude");
title("Input signal");
subplot(3,1,2);
stem(n,xe);
xlabel("Time");
ylabel("Amplitude");
title("Even signal");
subplot(3,1,3);
stem(n,xo);
xlabel("Time");
ylabel("Amplitude");
title("odd signal");
