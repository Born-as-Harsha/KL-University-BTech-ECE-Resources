clc;
clear all;
close all;
k = -300:300;
w = (pi/100) * k;
x = exp(j*w)./(exp(j*w) - 0.5*ones(size(w)));
magx = abs(x);
phasex = angle(x);
realx = real(x);
imaginaryx = imag(x);
subplot(2,2,1);
plot(w/pi, magx, 'r', 'LineWidth', 1.5);
xlabel('Frequency');
ylabel('Magnitude');
title('Magnitude Spectrum');
grid on;
subplot(2,2,2);
plot(w/pi, phasex, 'b', 'LineWidth', 1.5);
xlabel('Frequency');
ylabel('Phase');
title('Phase Spectrum');
grid on;
subplot(2,2,3);
plot(w/pi, realx, 'k', 'LineWidth', 1.5);
xlabel('Frequency');
ylabel('Real Part');
title('Real Spectrum');
grid on;
subplot(2,2,4);
plot(w/pi, imaginaryx, 'm', 'LineWidth', 1.5);
xlabel('Frequency');
ylabel('Imaginary Part');
title('Imaginary Spectrum');
grid on;
